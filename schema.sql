-- Menu items with "Item 86" toggle
CREATE TABLE IF NOT EXISTS menu_items (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  description TEXT,
  price NUMERIC(10,2) NOT NULL,
  category TEXT,
  image_url TEXT,
  is_available BOOLEAN DEFAULT TRUE
);

-- Backfill: add image_url to pre-existing databases (no-op if already present)
ALTER TABLE menu_items ADD COLUMN IF NOT EXISTS image_url TEXT;

-- Orders (dine-in vs takeaway)
CREATE TABLE IF NOT EXISTS orders (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  order_no INT GENERATED BY DEFAULT AS IDENTITY,
  customer_name TEXT,
  customer_phone TEXT,
  table_number INT,
  items JSONB NOT NULL,
  status TEXT DEFAULT 'pending',
  total_price NUMERIC(10,2),
  created_at TIMESTAMPTZ DEFAULT NOW()
);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS pickup_minutes INT;

CREATE INDEX IF NOT EXISTS orders_status_idx ON orders(status);
CREATE INDEX IF NOT EXISTS orders_created_idx ON orders(created_at DESC);
CREATE INDEX IF NOT EXISTS menu_items_category_idx ON menu_items(category);

-- Loyalty program (phone = primary key)
CREATE TABLE IF NOT EXISTS loyalty_customers (
  phone TEXT PRIMARY KEY,
  name TEXT,
  stamps INT DEFAULT 0
);

-- Site theme / design settings (single row, JSONB). Managed from admin "Design" tab.
CREATE TABLE IF NOT EXISTS settings (
  id TEXT PRIMARY KEY,
  theme JSONB NOT NULL DEFAULT '{}'::jsonb
);
