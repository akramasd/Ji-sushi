-- ---- Web Push subscriptions (kitchen iPad alerts) ----
CREATE TABLE IF NOT EXISTS push_subscriptions (
  endpoint TEXT PRIMARY KEY,
  keys JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE push_subscriptions ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE tablename = 'push_subscriptions' AND policyname = 'anon_all_push_subscriptions'
  ) THEN
    CREATE POLICY "anon_all_push_subscriptions" ON push_subscriptions FOR ALL
      USING (true) WITH CHECK (true);
  END IF;
END $$;
